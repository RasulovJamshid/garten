// Generate mobile form metadata from the same schemas used by the API.
const fs=require('fs'), path=require('path'),ts=require('typescript');
const root=path.resolve(__dirname,'../..');
function load(file,dependencies={}) {
 const exports={};
 const code=ts.transpileModule(fs.readFileSync(path.join(root,file),'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText;
 new Function('exports','require',code)(exports,name=>{if(name in dependencies)return dependencies[name];throw Error('Unexpected schema dependency: '+name);});
 return exports;
}
const permissions=load('src/rbac/permission-catalog.ts').PERMISSION_CATALOG;
const blocks=load('src/landing/block-content.ts',{'zod':require('zod'),'../common/exceptions/app.exception':{AppErrors:{}}}).BLOCK_SCHEMAS;
function schema(z){
 const d=z._def;
 if(d.typeName==='ZodOptional'||d.typeName==='ZodNullable')return {...schema(d.innerType),...(d.typeName==='ZodNullable'?{nullable:true}:{})};
 if(d.typeName==='ZodObject'){
  const shape=d.shape();
  return {type:'object',properties:Object.fromEntries(Object.entries(shape).map(([k,v])=>[k,{...schema(v),'x-visible':true}])),required:Object.entries(shape).filter(([_,v])=>!v.isOptional()).map(([k])=>k),additionalProperties:false};
 }
 if(d.typeName==='ZodArray')return {type:'array',items:schema(d.type),...(d.maxLength?{maxItems:d.maxLength.value}:{})};
 if(d.typeName==='ZodBoolean')return {type:'boolean'};
 if(d.typeName==='ZodString')return {type:'string',...Object.fromEntries((d.checks||[]).flatMap(c=>c.kind==='max'?[['maxLength',c.value]]:c.kind==='uuid'?[['format','uuid']]:c.kind==='email'?[['format','email']]:c.kind==='url'?[['format','uri']]:[]))};
 throw Error('Unhandled schema '+d.typeName);
}
const data={permissions:Object.fromEntries(permissions.map(p=>[p.key,{group:p.group,scopes:p.scopes}])),blocks:Object.fromEntries(Object.entries(blocks).map(([key,value])=>[key,schema(value)]))};
const target=path.join(root,'mobile/lib/core/workflow_metadata.dart');
const serialized=JSON.stringify(data,null,2);
const output="// Generated by tool/generate-workflows.cjs. Do not edit.\nimport 'dart:convert';\nimport 'api.dart';\n\nfinal workflowMetadata = object(jsonDecode(r'''\n"+serialized+"\n'''));\n";
if(process.argv.includes('--check')){
 const existing=fs.readFileSync(target,'utf8').split("r'''\n")[1]?.split("\n'''")[0];
 if(!existing||JSON.stringify(JSON.parse(existing))!==JSON.stringify(data))throw Error('Mobile workflow metadata is stale. Run npm run mobile:workflows.');
}else fs.writeFileSync(target,output);
console.log(permissions.length+' permission definitions and '+Object.keys(blocks).length+' content forms verified.');
