const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '../..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'assets/api-contract.json'), 'utf8'));
const read = name => fs.readFileSync(path.join(__dirname, name + '.tsv'), 'utf8').replace(/^\uFEFF/, '').trim().split(/\r?\n/).filter(x => x && !x.startsWith('#')).map(x => x.split('|'));
const nouns = Object.fromEntries(read('nouns').map(([key, ...v]) => [key, v]));
const labels = Object.fromEntries(['operations', 'fields', 'values', 'ui', 'responses'].flatMap(name => read(name)).map(([key, uz, ru]) => [key, [uz, ru]]));
for (const op of catalog.operations) {
  if (labels[op.id]) continue;
  const [controller, action] = op.id.split('_');
  const n = nouns[controller];
  if (!n) throw Error('Missing translation: ' + op.id);
  const [plural, ruPlural, singular, ruSingular, ruAcc] = n;
  const actions = {
    list: [plural, 'Список ' + ruPlural],
    get: [singular + ' ma’lumotlari', 'Карточка ' + ruSingular],
    create: [singular + ' qo‘shish', 'Добавить ' + ruAcc],
    update: [singular + ' ma’lumotlarini tahrirlash', 'Изменить ' + ruAcc],
    remove: [singular + 'ni o‘chirish', 'Удалить ' + ruAcc],
  };
  if (!actions[action]) throw Error('Missing translation: ' + op.id);
  labels[op.id] = actions[action];
}
const ts = require('typescript');
const compiled = ts.transpileModule(fs.readFileSync(path.join(root, '../src/rbac/permission-catalog.ts'), 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
const exported = {};
new Function('exports', compiled)(exported);
for (const p of exported.PERMISSION_CATALOG) labels[p.key] = [p.descriptionUz, p.descriptionRu];
const base = fs.readFileSync(path.join(root, 'lib/core/strings.dart'), 'utf8');
const existing = new Set([...base.matchAll(/'([^'\r\n]+)'\s*:/g)].map(m => m[1]));
for (const key of existing) delete labels[key];
const dart = '// Generated by tool/localization/generate.cjs. Edit the TSV sources.\nconst featureLabels = <String, List<String>>{\n' + Object.entries(labels).sort(([a], [b]) => a.localeCompare(b)).map(([key, value]) => '  ' + JSON.stringify(key) + ': ' + JSON.stringify(value) + ',').join('\n') + '\n};\n';
const target = path.join(root, 'lib/core/feature_labels.dart');
if (process.argv.includes('--check')) {
  const committed = fs.readFileSync(target, 'utf8');
  const parsed = Object.fromEntries([...committed.matchAll(/("(?:[^"\\]|\\.)*")\s*:\s*\[\s*("(?:[^"\\]|\\.)*")\s*,\s*("(?:[^"\\]|\\.)*")\s*,?\s*\]/g)].map(m => [JSON.parse(m[1]), [JSON.parse(m[2]), JSON.parse(m[3])]]));
  const normalize = map => JSON.stringify(Object.entries(map).sort(([a], [b]) => a.localeCompare(b)));
  if (normalize(parsed) !== normalize(labels)) throw Error('Mobile translations are stale. Run npm run mobile:localization and dart format mobile/lib/core/feature_labels.dart.');
} else {
  fs.writeFileSync(target, dart);
}
console.log('Generated ' + Object.keys(labels).length + ' bilingual labels for ' + catalog.operations.length + ' operations.');

